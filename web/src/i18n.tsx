export type Key = keyof typeof dict.zh;

const Ctx = createContext<{ lang: Lang; t: (k: Key) => string; setLang: (l: Lang) => void }>({
  lang: "zh",
  t: (k) => dict.zh[k],
  setLang: () => {},
});

export function I18n({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return (localStorage.getItem("lang") as Lang) || "zh";
    } catch {
      return "zh";
    }
  });
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("lang", l);
    } catch {}
    document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
  };
  return <Ctx.Provider value={{ lang, t: (k) => dict[lang][k], setLang }}>{children}</Ctx.Provider>;
}

export const useT = () => useContext(Ctx);
